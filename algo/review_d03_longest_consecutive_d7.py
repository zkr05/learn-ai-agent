def longest_consecutive(nums: list[int]) -> int:
    """最长连续整数序列的长度（不要求在原数组里相邻）。"""
    st = set(nums)
    ans = 0
    for x in st:
        if x-1 in st:
            continue
        y = x + 1
        while y in st:
            y += 1
        ans = max(ans, y-x)
    return ans


